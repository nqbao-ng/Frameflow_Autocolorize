export function getSupabaseAdmin() {
  const url = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;

  if (!url || !key) {
    throw new Error('Missing SUPABASE_URL/VITE_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY');
  }

  return createClient(url, key, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
}

export function sendJson(res, status, payload) {
  res.statusCode = status;
  res.setHeader('Content-Type', 'application/json');
  res.setHeader('Cache-Control', 'no-store');
  res.end(JSON.stringify(payload));
}

export function sendError(res, status, message, details = null) {
  sendJson(res, status, {
    ok: false,
    error: message,
    details,
  });
}

export async function readJsonBody(req) {
  if (req.body && typeof req.body === 'object') return req.body;

  const chunks = [];
  for await (const chunk of req) chunks.push(chunk);
  const raw = Buffer.concat(chunks).toString('utf8');
  if (!raw) return {};

  try {
    return JSON.parse(raw);
  } catch (error) {
    throw new Error('Invalid JSON body');
  }
}

export function ensureMethod(req, res, allowed) {
  if (!allowed.includes(req.method)) {
    res.setHeader('Allow', allowed.join(', '));
    sendError(res, 405, `Method ${req.method} not allowed`);
    return false;
  }
  return true;
}

export async function getLatestJob(supabase, projectId, jobId = null) {
  let query = supabase
    .from('colorization_jobs')
    .select('*')
    .eq('project_id', projectId);

  if (jobId) {
    query = query.eq('id', jobId).single();
  } else {
    query = query.order('created_at', { ascending: false }).limit(1).maybeSingle();
  }

  const { data, error } = await query;
  if (error) throw error;
  return data;
}

export async function getProjectFrames(supabase, projectId) {
  const { data, error } = await supabase
    .from('frames')
    .select('*')
    .eq('project_id', projectId)
    .order('frame_index', { ascending: true });

  if (error) throw error;
  return data || [];
}

