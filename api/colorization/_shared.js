export function defaultRolePalette(roleMemory = []) {
  const memoryColors = roleMemory
    .map((row) => row.locked_color)
    .filter(Boolean);

  const fallback = [
    '#F2B08C',
    '#1E293B',
    '#3B82F6',
    '#8B5CF6',
    '#10B981',
    '#F59E0B',
    '#EF4444',
    '#E5E7EB',
  ];

  return Array.from(new Set([...memoryColors, ...fallback])).slice(0, 12);
}

export function normalizeCorrectionList(body) {
  const corrections = Array.isArray(body.corrections)
    ? body.corrections
    : [
        {
          segment_id: body.segment_id,
          role_id: body.role_id || body.role,
          color_hex: body.color_hex,
          palette_locked: body.palette_locked,
          source: body.source || body.correction_source,
        },
      ];

  return corrections
    .filter((item) => item && item.segment_id !== undefined && item.color_hex)
    .map((item) => ({
      segment_id: Number(item.segment_id),
      role_id: item.role_id || 'unknown',
      color_hex: item.color_hex,
      palette_locked: item.palette_locked !== false,
      source: item.source || 'user_manual',
      confidence: item.confidence ?? 1.0,
      metadata: item.metadata || {},
    }));
}
